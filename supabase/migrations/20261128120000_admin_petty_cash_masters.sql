CREATE OR REPLACE FUNCTION public.overhead_category_before_write()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
  v_next int;
BEGIN
  NEW.name := btrim(NEW.name);
  IF TG_OP = 'INSERT' THEN
    PERFORM pg_advisory_xact_lock(hashtext('public.overhead_category.code'));
    SELECT COALESCE(MAX(NULLIF(regexp_replace(code, '\D', '', 'g'), '')::int), 0) + 1
      INTO v_next
      FROM public.overhead_category
     WHERE code ~ '^OH-\d+$';
    NEW.code := 'OH-' || lpad(v_next::text, 3, '0');
  ELSE
    NEW.code := OLD.code; -- code is read-only once assigned
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_overhead_category_before_write ON public.overhead_category;
CREATE TRIGGER trg_overhead_category_before_write
  BEFORE INSERT OR UPDATE ON public.overhead_category
  FOR EACH ROW EXECUTE FUNCTION public.overhead_category_before_write();

CREATE OR REPLACE FUNCTION public.overhead_category_before_delete()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_count int;
BEGIN
  SELECT count(*) INTO v_count FROM public.expense_category WHERE overhead_category_id = OLD.id;
  IF v_count > 0 THEN
    RAISE EXCEPTION 'Cannot delete "%": it has % expense categor%. Delete or move them first.',
      OLD.name, v_count, CASE WHEN v_count = 1 THEN 'y' ELSE 'ies' END
      USING ERRCODE = 'P0001', HINT = 'petty_cash_overhead_in_use';
  END IF;
  RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS trg_overhead_category_before_delete ON public.overhead_category;
CREATE TRIGGER trg_overhead_category_before_delete
  BEFORE DELETE ON public.overhead_category
  FOR EACH ROW EXECUTE FUNCTION public.overhead_category_before_delete();

CREATE OR REPLACE FUNCTION public.expense_category_before_write()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
DECLARE
  v_count int;
BEGIN
  NEW.name := btrim(NEW.name);
  IF TG_OP = 'UPDATE' AND NEW.overhead_category_id IS DISTINCT FROM OLD.overhead_category_id THEN
    SELECT count(*) INTO v_count FROM public.petty_cash_voucher WHERE expense_category_id = OLD.id;
    IF v_count > 0 THEN
      RAISE EXCEPTION 'Cannot move "%" to another overhead: it already has % voucher%.',
        OLD.name, v_count, CASE WHEN v_count = 1 THEN '' ELSE 's' END
        USING ERRCODE = 'P0001', HINT = 'petty_cash_category_has_vouchers';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

