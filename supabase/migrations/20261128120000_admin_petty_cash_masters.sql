-- Admin → Petty Cash: Overhead & Expense Master + Daily Expense Entry vouchers.
--
--   overhead_category   id, name (unique, case-insensitive), code (auto OH-001), created_at
--   expense_category    id, overhead_category_id (required FK), name (unique per overhead), created_at
--   petty_cash_voucher  one petty cash expense, always tied to one overhead + one of its expense categories
--
-- Access is explicit-grant only (mirrors src/pages/adminOperations/pettyCash/pettyCashPermissions.js).
-- The Admin role, Admin team or full Admin module do NOT grant Petty Cash; this migration grants
-- nothing to existing or new users. Access is given per user in User Management:
--   View / enter expenses  → Super Admin / Super Admin Pro, or admin.petty-cash (or any admin.petty-cash.* key)
--   Manage masters         → Super Admin / Super Admin Pro, or admin.petty-cash.manage-masters
--
-- Deletes are blocked with a readable message when an overhead still has expense categories,
-- or an expense category still has vouchers (trigger + RESTRICT FK as a backstop).
--
-- Rollback: supabase/rollbacks/20261128120000_admin_petty_cash_masters_down.sql

-- ---------------------------------------------------------------------------
-- Access helpers
-- ---------------------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.current_user_can_manage_petty_cash_masters()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = auth.uid()
      AND auth.uid() IS NOT NULL
      AND COALESCE(p.is_active, true)
      AND (
        public.normalize_erp_role(p.role) IN ('super_admin', 'super_admin_pro')
        OR public.jsonb_text_array(to_jsonb(p) -> 'allowed_sub_modules') ? 'admin.petty-cash.manage-masters'
      )
  );
$$;

COMMENT ON FUNCTION public.current_user_can_manage_petty_cash_masters() IS
  'True when the caller may add / edit / delete Petty Cash overhead and expense categories. Super Admin always; everyone else only with admin.petty-cash.manage-masters (the Admin role / Admin module do not grant it).';

CREATE OR REPLACE FUNCTION public.current_user_can_view_petty_cash()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
SET row_security = off
AS $$
  SELECT public.current_user_can_manage_petty_cash_masters()
    OR EXISTS (
      SELECT 1
      FROM public.profiles p
      WHERE p.id = auth.uid()
        AND auth.uid() IS NOT NULL
        AND COALESCE(p.is_active, true)
        AND EXISTS (
          SELECT 1
          FROM jsonb_array_elements_text(public.jsonb_text_array(to_jsonb(p) -> 'allowed_sub_modules')) AS s(value)
          WHERE s.value = 'admin.petty-cash' OR s.value LIKE 'admin.petty-cash.%'
        )
    );
$$;

COMMENT ON FUNCTION public.current_user_can_view_petty_cash() IS
  'True when the caller may open Admin → Petty Cash (read masters, enter daily expenses). Super Admin always; everyone else only with admin.petty-cash (or a admin.petty-cash.* key) ticked in User Management. Admin role, team and allowed_modules do not grant it.';

REVOKE ALL ON FUNCTION public.current_user_can_manage_petty_cash_masters() FROM PUBLIC, anon;
REVOKE ALL ON FUNCTION public.current_user_can_view_petty_cash() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.current_user_can_manage_petty_cash_masters() TO authenticated, service_role;
GRANT EXECUTE ON FUNCTION public.current_user_can_view_petty_cash() TO authenticated, service_role;

