-- Enquiry serial numbers form one continuous series 1..N (in existing order).
-- New enquiries continue from the last number; deleting an enquiry closes the gap.

alter table projects.enquiries alter column serial_number set generated by default;

-- Renumbering is not an edit: keep updated_at unchanged when only the serial moves.
drop trigger if exists enquiries_updated_at on projects.enquiries;
create trigger enquiries_updated_at
  before update on projects.enquiries
  for each row
  when (old.serial_number is not distinct from new.serial_number)
  execute function public.set_updated_at();

create or replace function projects.renumber_enquiry_serials()
returns void
language plpgsql
security definer
set search_path = projects, pg_temp
as $$
declare
  v_max bigint;
begin
  perform pg_advisory_xact_lock(hashtext('projects.enquiries.serial_number'));

  with ordered as (
    select id, row_number() over (order by serial_number nulls last, created_at, id) as rn
    from projects.enquiries
  )
  update projects.enquiries e
     set serial_number = o.rn
    from ordered o
   where o.id = e.id
     and e.serial_number is distinct from o.rn;

  select coalesce(max(serial_number), 0) into v_max from projects.enquiries;
  if v_max = 0 then
    perform setval(pg_get_serial_sequence('projects.enquiries', 'serial_number'), 1, false);
  else
    perform setval(pg_get_serial_sequence('projects.enquiries', 'serial_number'), v_max, true);
  end if;
end;
$$;

revoke all on function projects.renumber_enquiry_serials() from public;

create or replace function projects.enquiries_after_delete_renumber()
returns trigger
language plpgsql
security definer
set search_path = projects, pg_temp
as $$
begin
  perform projects.renumber_enquiry_serials();
  return null;
end;
$$;

revoke all on function projects.enquiries_after_delete_renumber() from public;

drop trigger if exists enquiries_renumber_after_delete on projects.enquiries;
create trigger enquiries_renumber_after_delete
  after delete on projects.enquiries
  for each statement
  execute function projects.enquiries_after_delete_renumber();

select projects.renumber_enquiry_serials();
