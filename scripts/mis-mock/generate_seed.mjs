const COST_CENTRES = { manpower: 'CC-A', amc: 'CC-B', projects: 'CC-C', corporate: 'CC-CORP' };

function doj(e) {
  if (e.joiner) return e.joiner.doj;
  if (e.fromMonth) return `${e.fromMonth}-01`;
  const base = Date.UTC(2016, 3, 1) + (e.n * 11 % 3000) * 86400000;
  return new Date(base).toISOString().slice(0, 10);
}

function employmentType(e) {
  if (e.joiner) return 'probation';
  if (e.esi && e.rate <= 1120000) return 'contract';
  return 'permanent';
}

// New hires: full monthly CTC adds up to 3,42,000 (average 28,500).
const joiners = m.employees.filter((e) => e.joiner);
const joinerRateSum = joiners.reduce((s, e) => s + e.rateSep, 0);
const ctcFull = new Map();
let ctcLeft = 34200000;
joiners.forEach((e, i) => {
  const v = i === joiners.length - 1 ? ctcLeft : Math.round((e.rateSep * 34200000) / joinerRateSum / 100) * 100;
  ctcFull.set(e.n, v);
  ctcLeft -= v;
});

let exitIdx = 0;
const empRows = m.employees.map((e) => {
  const s = m.struct['2026-04'].get(e.n);
  const isExit = e.kind === 'exit';
  const reason = isExit ? EXIT_REASONS[exitIdx++ % EXIT_REASONS.length] : null;
  const rateSep = e.rateSep;
  const basic = Math.round(rateSep / 2 / 100) * 100;
  const hra = Math.round((rateSep * 0.2) / 100) * 100;
  return [
    e.n, q(code(e.n)), q(`Mock Employee ${pad(e.n, 3)}`), q(e.bucket), q(e.vertical), q(e.dept), q(e.designation),
    q(e.location), q(employmentType(e)), q(doj(e)), isExit ? q('2026-09-01') : 'NULL', q(isExit ? 'Inactive' : 'Active'),
    q(reason), e.pf ? q(`9999${pad(e.n, 8)}`) : 'NULL', e.esi ? q(`9999${pad(e.n, 6)}`) : 'NULL', q(e.grade),
    q(COST_CENTRES[e.vertical]), q(e.joiner ? e.joiner.pos : null), q(reason),
    money(rateSep), money(basic), money(hra), money(rateSep - basic - hra),
    money(s.grat), money(s.bonus), money(s.med),
    q(e.kind === 'incr' ? 'increment' : 'initial'), q(e.kind === 'incr' ? '2026-09-01' : doj(e)),
    ctcFull.has(e.n) ? money(ctcFull.get(e.n)) : 'NULL',
  ].join(', ');
});

const lineRows = [];
