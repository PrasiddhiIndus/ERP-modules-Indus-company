export async function runScript(db, sqlText) {
  try {
    await db.exec(sqlText);
    return null;
  } catch (e) {
    try {
      await db.exec('ROLLBACK');
    } catch {
      // no open transaction
    }
    return e.message || String(e);
  }
}

/** Report inputs as the app reads them (RPCs), with dates as YYYY-MM-DD strings. */
export async function readReportData(db, from = '2025-10', to = '2026-12') {
  const rows = await json(db, 'SELECT to_jsonb(r) AS j FROM public.admin_payroll_mis_rows($1, $2) r', [from, to]);
  const months = await json(db, 'SELECT to_jsonb(m) AS j FROM public.admin_payroll_mis_months() m');
  const payments = await json(db, `SELECT to_jsonb(p) AS j FROM public.admin_payroll_statutory_payments p
    WHERE wage_month BETWEEN $1 AND $2 ORDER BY wage_month, statute`, [from, to]);
  const allocations = await json(db, 'SELECT to_jsonb(a) AS j FROM public.admin_payroll_cost_allocations a');
  const rates = await json(db, 'SELECT to_jsonb(r) AS j FROM public.admin_payroll_statutory_rates r');
  let register = [];
  try {
    register = await json(db, 'SELECT to_jsonb(t) AS j FROM public.admin_payroll_mis_register_totals($1, $2) t', [from, to]);
  } catch {
    register = [];
  }
  return { rows, months, payments, allocations, rates, register };
}
