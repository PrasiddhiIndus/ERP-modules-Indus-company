const chunk = (rows, size = 400) => {
  const out = [];
  for (let i = 0; i < rows.length; i += size) out.push(rows.slice(i, i + size));
  return out;
};
const valuesInsert = (table, cols, rows) => chunk(rows)
  .map((c) => `INSERT INTO ${table} (${cols}) VALUES\n  (${c.join('),\n  (')});`).join('\n');

