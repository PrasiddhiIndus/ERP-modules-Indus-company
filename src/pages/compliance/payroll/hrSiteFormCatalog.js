export function formDisplayName(form) {
  if (!form) return "";
  return `${form.formNo} – ${form.name}`;
}

/** Map UI site type (Fire/Safety) or module (IH) to appliesTo code. */
export function appliesCodeForContext(module, siteType) {
  if (module === "IH") return "IH";
  if (siteType === "Safety") return "SAFETY";
  return "FIRE";
}

