export function inferSiteState(site) {
  const hay = `${site?.location || ""} ${site?.site_name || ""}`.toLowerCase();
  for (const [needle, label] of STATE_HINTS) {
    if (hay.includes(needle.trim())) return label;
  }
  return "";
}

/** Eligible active forms for a site under current Fire/Safety (or IH) context. */
export function eligibleFormsForSite(forms, site, appliesCode) {
  const state = inferSiteState(site);
  return (forms || []).filter((form) => {
    if (!form?.active) return false;
    if (!(form.appliesTo || []).includes(appliesCode)) return false;
    if (form.type === "Central") return true;
    if (form.anyState) return true;
    if (!form.state) return true;
    return state && form.state.toLowerCase() === state.toLowerCase();
  });
}
