const json = async (db, sqlText, params = []) => (await db.query(sqlText, params)).rows.map((r) => r.j);

/** Full ordered dump of the watched tables (to prove seed + cleanup leave real data exactly as before). */
export async function dumpTables(db) {
  const out = {};
  for (const t of WATCHED_TABLES) {
    const name = t.includes('.') ? t : `public.${t}`;
    const rows = await json(db, `SELECT to_jsonb(x) AS j FROM ${name} x`);
    out[t] = rows.map((r) => JSON.stringify(r)).sort();
  }
  return out;
}

export async function rowCounts(db) {
  const out = {};
  for (const t of WATCHED_TABLES) {
    const name = t.includes('.') ? t : `public.${t}`;
    out[t] = Number((await db.query(`SELECT count(*)::int AS n FROM ${name}`)).rows[0].n);
  }
  return out;
}

