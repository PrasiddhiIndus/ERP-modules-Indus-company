DROP VIEW IF EXISTS public.overhead_category_usage;

CREATE TABLE IF NOT EXISTS public.expense_category (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  overhead_category_id  bigint NOT NULL REFERENCES public.overhead_category(id) ON DELETE RESTRICT,
  name                  text NOT NULL CHECK (btrim(name) <> ''),
  created_at            timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT uq_expense_category_id_overhead UNIQUE (id, overhead_category_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_expense_category_overhead_name
  ON public.expense_category (overhead_category_id, lower(btrim(name)));

-- Recreate categories from distinct free-text names used on vouchers.
INSERT INTO public.expense_category (overhead_category_id, name)
SELECT DISTINCT v.overhead_category_id, btrim(v.expense_category_name)
FROM public.petty_cash_voucher v
WHERE btrim(COALESCE(v.expense_category_name, '')) <> ''
ON CONFLICT DO NOTHING;

ALTER TABLE public.petty_cash_voucher
  ADD COLUMN IF NOT EXISTS expense_category_id bigint;

UPDATE public.petty_cash_voucher v
SET expense_category_id = ec.id
FROM public.expense_category ec
WHERE ec.overhead_category_id = v.overhead_category_id
  AND lower(btrim(ec.name)) = lower(btrim(v.expense_category_name));

-- Any remaining vouchers get a fallback "Unspecified" category under their overhead.
INSERT INTO public.expense_category (overhead_category_id, name)
SELECT DISTINCT v.overhead_category_id, 'Unspecified'
FROM public.petty_cash_voucher v
WHERE v.expense_category_id IS NULL
ON CONFLICT DO NOTHING;

UPDATE public.petty_cash_voucher v
SET expense_category_id = ec.id
FROM public.expense_category ec
WHERE v.expense_category_id IS NULL
  AND ec.overhead_category_id = v.overhead_category_id
  AND lower(btrim(ec.name)) = 'unspecified';

