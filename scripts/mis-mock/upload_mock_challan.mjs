/**
 * Uploads one dummy challan PDF ("MOCK — not a real payment") for the mock Sep 2026 TDS deposit,
 * so Report 7's "open challan" link can be tested. Local / staging only.
 *
 *   MIS_MOCK_CONFIRM=not-production node scripts/mis-mock/upload_mock_challan.mjs
 *   MIS_MOCK_CONFIRM=not-production node scripts/mis-mock/upload_mock_challan.mjs --remove   (before cleanup)
 *
 * Needs SUPABASE_URL (or VITE_SUPABASE_URL) and SUPABASE_SERVICE_ROLE_KEY in the environment or .env.
 * Touches only the mock payment row (challan MOCK-CIN-0510221 on a salary month flagged mock_mis).
 */
import { existsSync } from 'node:fs';
import { createClient } from '@supabase/supabase-js';
import { jsPDF } from 'jspdf';

const BUCKET = 'payroll-statutory-challans';
const remove = process.argv.includes('--remove');

if (existsSync('.env') && typeof process.loadEnvFile === 'function') process.loadEnvFile('.env');
const url = process.env.SUPABASE_URL || process.env.VITE_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error('Set SUPABASE_URL (or VITE_SUPABASE_URL) and SUPABASE_SERVICE_ROLE_KEY for the local / staging project.');
  process.exit(1);
}
console.log(`Target project: ${url}`);
if (process.env.MIS_MOCK_CONFIRM !== 'not-production') {
  console.error('Refusing to run: set MIS_MOCK_CONFIRM=not-production after checking the target above is local / staging.');
  process.exit(1);
}

const sb = createClient(url, key, { auth: { persistSession: false } });

const { data: payment, error } = await sb.from('admin_payroll_statutory_payments')
  .select('id, wage_month, statute, state, run_id, challan_ref, challan_path')
  .eq('wage_month', '2026-09').eq('statute', 'TDS').eq('challan_ref', 'MOCK-CIN-0510221')
  .maybeSingle();
if (error || !payment) {
  console.error('Mock Sep 2026 TDS payment not found. Run seed_mis_mock.sql first.', error?.message || '');
  process.exit(1);
}
const { data: run } = await sb.from('admin_salary_month_runs').select('summary_json').eq('id', payment.run_id).maybeSingle();
if (run?.summary_json?.mock_mis !== true) {
  console.error('That payment does not belong to a mock salary month. Nothing changed.');
  process.exit(1);
}

if (remove) {
  if (payment.challan_path && payment.challan_path.includes('mock-challan')) {
    const del = await sb.storage.from(BUCKET).remove([payment.challan_path]);
    if (del.error) throw new Error(del.error.message);
  }
  const upd = await sb.from('admin_payroll_statutory_payments').update({ challan_path: null }).eq('id', payment.id);
  if (upd.error) throw new Error(upd.error.message);
  console.log('Dummy challan removed.');
  process.exit(0);
}

const doc = new jsPDF();
doc.setFontSize(18);
doc.text('MOCK CHALLAN — NOT A REAL PAYMENT', 15, 25);
doc.setFontSize(11);
[
  'Payroll MIS test data (mock_mis). Generated by scripts/mis-mock/upload_mock_challan.mjs.',
  `Statute: TDS on salary   Wage month: Sep 2026   State: ${payment.state}`,
  'Challan / CIN: MOCK-CIN-0510221   Paid on: 06 Oct 2026   Amount: Rs 3,20,000',
  'No bank, PAN, TAN or employee details. Delete with --remove before running the cleanup script.',
].forEach((line, i) => doc.text(line, 15, 40 + i * 8));
const body = Buffer.from(doc.output('arraybuffer'));
const path = `${payment.wage_month}/${payment.statute}-${payment.state}-${payment.id}-mock-challan.pdf`;

const up = await sb.storage.from(BUCKET).upload(path, body, { contentType: 'application/pdf', upsert: true });
if (up.error) throw new Error(up.error.message);
const upd = await sb.from('admin_payroll_statutory_payments')
  .update({ challan_path: path, updated_at: new Date().toISOString() }).eq('id', payment.id);
if (upd.error) throw new Error(upd.error.message);
console.log(`Dummy challan uploaded: ${BUCKET}/${path}`);
