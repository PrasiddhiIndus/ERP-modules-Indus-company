CREATE TABLE IF NOT EXISTS public.overhead_category (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL CHECK (btrim(name) <> ''),
  code        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_overhead_category_name
  ON public.overhead_category (lower(btrim(name)));
CREATE UNIQUE INDEX IF NOT EXISTS uq_overhead_category_code
  ON public.overhead_category (code);

COMMENT ON TABLE public.overhead_category IS
  'Petty Cash overhead categories (top-level groups). Code is assigned automatically as OH-001, OH-002, …';

CREATE TABLE IF NOT EXISTS public.expense_category (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  overhead_category_id  bigint NOT NULL REFERENCES public.overhead_category(id) ON DELETE RESTRICT,
  name                  text NOT NULL CHECK (btrim(name) <> ''),
  created_at            timestamptz NOT NULL DEFAULT now(),
  -- Lets vouchers reference (id, overhead) so a voucher can never point at a category of another overhead.
  CONSTRAINT uq_expense_category_id_overhead UNIQUE (id, overhead_category_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_expense_category_overhead_name
  ON public.expense_category (overhead_category_id, lower(btrim(name)));

COMMENT ON TABLE public.expense_category IS
  'Petty Cash expense categories. Each belongs to exactly one overhead category.';

CREATE TABLE IF NOT EXISTS public.petty_cash_voucher (
  id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  voucher_no            text NOT NULL,
  expense_date          date NOT NULL,
  payment_mode          text NOT NULL CHECK (payment_mode IN ('Cash', 'UPI', 'Bank', 'Other')),
  overhead_category_id  bigint NOT NULL REFERENCES public.overhead_category(id) ON DELETE RESTRICT,
  expense_category_id   bigint NOT NULL,
  description           text NOT NULL CHECK (char_length(btrim(description)) >= 5),
  amount                numeric(14, 2) NOT NULL CHECK (amount > 0),
  paid_to               text NOT NULL CHECK (btrim(paid_to) <> ''),
  remarks               text,
  created_by            uuid DEFAULT auth.uid() REFERENCES public.profiles(id),
  created_at            timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fk_petty_cash_voucher_expense_category
    FOREIGN KEY (expense_category_id, overhead_category_id)
    REFERENCES public.expense_category (id, overhead_category_id)
    ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_petty_cash_voucher_no ON public.petty_cash_voucher (voucher_no);
CREATE INDEX IF NOT EXISTS idx_petty_cash_voucher_category_date
  ON public.petty_cash_voucher (expense_category_id, expense_date);
CREATE INDEX IF NOT EXISTS idx_petty_cash_voucher_date ON public.petty_cash_voucher (expense_date DESC);

COMMENT ON TABLE public.petty_cash_voucher IS
  'Petty Cash daily expense vouchers (PCV-YYMM-NNNN). Expense category must sit under the chosen overhead.';

