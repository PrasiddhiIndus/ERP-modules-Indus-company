-- =============================================================================
-- Daily Attendance Register: remove WO / NH·PH marks before each employee's DOJ.
--
-- Mid-month joiners must not keep auto (or leftover) weekly-off / holiday marks
-- on calendar days strictly before date_of_joining. Grid/summary already blank
-- those days when DOJ is known; this cleans the stored register so totals and
-- exports stay consistent.
--
-- Keeps all marks on/after DOJ. Does not touch leave, punches after DOJ, or C/O.
-- Rollback: supabase/rollbacks/20261123130000_register_clear_pre_doj_offs_down.sql
-- (no-op restore — deleted pre-DOJ offs are regenerated by auto WO/NH sync only
--  for dates on/after DOJ).
-- =============================================================================

DELETE FROM public.admin_attendance_register r
USING public.admin_ifsp_employee_master m
WHERE public.normalize_attendance_employee_code(m.employee_code)
    = public.normalize_attendance_employee_code(r.employee_code)
  AND m.date_of_joining IS NOT NULL
  AND r.register_date < m.date_of_joining
  AND (
    r.mark = 'WO'
    OR r.mark IN ('NH/PH', 'NHPH')
    OR coalesce(r.mark_source, '') IN ('auto_wo', 'auto_holiday')
  );

NOTIFY pgrst, 'reload schema';
